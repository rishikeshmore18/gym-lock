//  The 5 x 7 dot font and the small pixel icons the printer prints with. Port of the approved
//  prototype's GLYPH table (docs/prototypes/plans-changed-pause: v-mprinter.html). A glyph is rows
//  of 0/1; descender rows follow the body rows. A glyph's width is its body row length, centred
//  in a 5-dot cell.
//

import CoreGraphics
import Foundation

nonisolated struct PrinterDotGlyph {
    /// Body rows first, then descender rows. `true` is a lit dot.
    let rows: [[Bool]]
    /// Width of the body rows, in dots.
    let width: Int
}

nonisolated enum PrinterDotFont {
    static func glyph(_ ch: Character) -> PrinterDotGlyph? { table[ch] }

    /// Parsed once.
    private static let table: [Character: PrinterDotGlyph] = parse(source)

    private static func parse(_ text: String) -> [Character: PrinterDotGlyph] {
        var out: [Character: PrinterDotGlyph] = [:]
        for rawLine in text.split(separator: "\n") {
            let line = rawLine.trimmingCharacters(in: .whitespaces)
            guard let ch = line.first else { continue }
            let rest = line.dropFirst(2)
            let parts = rest.split(separator: " ", omittingEmptySubsequences: true).map(String.init)
            guard !parts.isEmpty else { continue }
            var body: [String] = []
            var desc: [String] = []
            if let bar = parts.firstIndex(of: "|") {
                body = Array(parts[..<bar])
                desc = Array(parts[(bar + 1)...])
            } else {
                body = parts
            }
            guard let first = body.first else { continue }
            let rows = (body + desc).map { row in row.map { $0 == "1" } }
            out[ch] = PrinterDotGlyph(rows: rows, width: first.count)
        }
        return out
    }

