// Golden values for all 133 Matrix scenes (19 moments x 7 themes), computed from the TS sources.
// Prints a Swift file (MatrixParityAll.swift) to stdout. Run through run-golden.sh --all.
//
// Order matters: setup.ts keeps per-day memory between draws (MEM), so the Swift test replays
// exactly this order: moments in MOMENTS order, scenes 0...6, contexts in CTX order.

import {G} from '../../web-reference/hero13/mxlib';

const MOMENTS = ['setup', 'firstnight', 'bedtime', 'wake', 'countdown', 'ready', 'commute', 'atgym', 'verified', 'stilltime', 'rest', 'paused', 'freshstart', 'missed', 'weekkept', 'comeback', 'drift', 'halfway', 'automatic'];

const f = (x: number) => +x.toPrecision(12);
const sum = (o: any[]) => o.reduce((a, q) => a + q.x * 1.3 + q.y * 0.7 + q.b * 5 + (q.c ? 11 : 0) + (q.id % 9973) * 0.001, 0);

/** contexts: T values across the intro beats and the idle loop, with live numbers that light most branches */
type C = {T: number; t: number; day: number; pos: string; N: number; atgym: number; countdown: number; still: number; done: boolean[]};
const CTX: C[] = [
  {T: 0.15, t: 40.15, day: 0, pos: 'first', N: 5, atgym: 310.4, countdown: 5400, still: 21000, done: [true, false, false]},
  {T: 0.9, t: 40.9, day: 2, pos: 'middle', N: 5, atgym: 845.2, countdown: 3725.3, still: 7300, done: [true, false, true]},
  {T: 2.4, t: 42.4, day: 4, pos: 'last', N: 7, atgym: 1260.7, countdown: 900.5, still: 3400, done: [true, true, true]},
  {T: 7.3, t: 47.3, day: 6, pos: 'last', N: 7, atgym: 2210, countdown: 61.2, still: 600, done: [true, true, true]},
];
const mc = (c: C) => ({t: c.t, T: c.T, d: {setupDone: c.done, countdown: c.countdown, atgym: c.atgym, stillLeft: c.still}, day: c.day, pos: c.pos, N: c.N, D: {day: 23, week: 3, sessions: 14}});

const run = async () => {
  const rows: string[] = [];
  for (const m of MOMENTS) {
    const mod = await import(`../../web-reference/hero13/mx/${m}`);
    const S = mod.SCENES as any[];
    if (S.length !== 7) throw new Error(`${m}: ${S.length} scenes`);
    S.forEach((sc, i) => {
      CTX.forEach((c, k) => {
        const g = new G();
        const o = sc.draw(g, mc(c)) || {};
        const out = g.out();
        const ph = o.ph === undefined || o.ph === 0 ? 'nil' : JSON.stringify(String(o.ph));
        rows.push(`        ("${m}", ${i}, ${k}, ${out.length}, ${f(sum(out))}, ${ph}, ${f(o.flash ?? 0)}, ${f(o.shake ?? 0)}),`);
      });
    });
  }
  const ctx = CTX.map((c) => `        MatrixContext(t: ${c.t}, T: ${c.T}, d: MatrixLiveData(setupDone: [${c.done.join(', ')}], countdown: ${c.countdown}, atgym: ${c.atgym}, stillLeft: ${c.still}), day: ${c.day}, pos: .${c.pos}, N: ${c.N}, D: MatrixDayData(day: 23, week: 3, sessions: 14)),`);
  console.log(`//
//  MatrixParityAll.swift
//  GymLock · Matrix hero
//
//  GENERATED by docs/hero-pack/swift/tools/run-golden.sh --all from the TypeScript sources.
//  Golden target counts, checksums, phases, flash and shake for all 133 scenes at 4 contexts.
//  Do not edit by hand.
//

#if DEBUG
import Foundation

extension MatrixParity {
    static let allContexts: [MatrixContext] = [
${ctx.join('\n')}
    ]

    /// (moment, theme, context index, targets, checksum, phase, flash, shake), in replay order.
    static let allGolden: [(String, Int, Int, Int, Double, String?, Double, Double)] = [
${rows.join('\n')}
    ]
}
#endif`);
};
run();
